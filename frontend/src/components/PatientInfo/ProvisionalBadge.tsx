import type { ReactNode } from 'react';
import { useProvisionalMark } from './ProvisionalContext';

/** "Provisional 82%" after a field's label when its value is a proposal. */
export default function ProvisionalBadge({ name }: { name: string }) {
  const mark = useProvisionalMark(name);
  if (!mark) return null;
  const title = mark.patientMode
    ? 'Not yet confirmed. This value comes from a record that has not been fully checked. '
      + 'If it is wrong or right, you can enter it yourself.'
    : `From a code mapping that is not approved yet (${mark.confidence}% confidence). `
      + 'Edit the field to confirm it as approved data.';
  return (
    <span
      className="rounded bg-amber-100 px-1.5 py-0.5 text-xs font-medium text-amber-800"
      title={title}
      data-testid={`provisional-${name}`}
    >
      Provisional {mark.confidence}%
    </span>
  );
}

/**
 * Around a control that does not render through `Field` (the treating
 * institution picker, the GELF and FLIPI checklists): the same indicator above
 * it when `name`, the record field it shows, holds a proposal. `name` is quoted
 * at the call site on purpose: `patientVisibleFields.json` is generated by
 * scanning the tabs for such names, so a control marked this way also stops the
 * patient confirming their record (#2761).
 */
export function MarkedControl({ name, children }: { name: string; children: ReactNode }) {
  const mark = useProvisionalMark(name);
  return (
    <>
      {mark && <div className="mb-1"><ProvisionalBadge name={name} /></div>}
      {children}
    </>
  );
}
